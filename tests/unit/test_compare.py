from __future__ import annotations

from pathlib import Path

from sqlvec import compare

DOC = Path(__file__).resolve().parents[2] / "docs" / "compare-pgvector.md"
BEGIN = "<!-- BEGIN compare-pg (generated by `sqlvec compare-pg --format markdown`) -->"
END = "<!-- END compare-pg -->"


def test_every_row_has_both_sides() -> None:
    assert len(compare.ROWS) >= 15
    for r in compare.ROWS:
        assert r.operation and r.sql_server and r.pgvector


def test_key_operations_present() -> None:
    ops = {r.operation for r in compare.ROWS}
    for needed in ("Cosine distance", "ANN index", "ANN query", "Hybrid (RRF)", "Keyword search"):
        assert needed in ops
    by_op = {r.operation: r for r in compare.ROWS}
    assert "<=>" in by_op["Cosine distance"].pgvector
    assert "VECTOR_DISTANCE('cosine'" in by_op["Cosine distance"].sql_server
    assert "WITH APPROXIMATE" in by_op["ANN query"].sql_server


def test_markdown_escapes_pipes_and_has_header() -> None:
    md = compare.to_markdown()
    assert md.startswith("| operation | SQL Server 2025 / Azure SQL | PostgreSQL + pgvector |")
    for line in md.splitlines()[2:]:
        assert line.count(" | ") + line.count("` | ") >= 3


def test_text_format() -> None:
    text = compare.to_text()
    assert "SQL Server : VECTOR_DISTANCE('cosine', embedding, @qv)" in text


def test_doc_is_in_sync_with_code() -> None:
    text = DOC.read_text(encoding="utf-8")
    start = text.index(BEGIN) + len(BEGIN)
    end = text.index(END)
    assert text[start:end].strip() == compare.to_markdown().strip(), (
        "docs/compare-pgvector.md is stale: regenerate the table with "
        "`sqlvec compare-pg --format markdown`"
    )
